_VOLATILE_KEYS = ("path", "seconds", "time", "duration", "elapsed", "created_at")


def _strip_volatile(value: Any) -> Any:
    """Drop the fields that differ between any two runs (paths, timings)."""
    if isinstance(value, dict):
        return {
            k: _strip_volatile(v)
            for k, v in value.items()
            if not any(t in str(k).lower() for t in _VOLATILE_KEYS)
        }
    if isinstance(value, list):
        return [_strip_volatile(v) for v in value]
    return value


def _scenario_pipeline(
    name: str, parallel_mode: str, ctx: dict[str, Any]
) -> dict[str, Any]:
    from configurable_automl_engine import ModelTrainer, train_best_model

    make_df, oversampling = _PIPELINES[name]
    df = make_df()
    model_path = Path(ctx["workdir"]) / f"pipeline_{name}_{parallel_mode}.pkl"
    result = train_best_model(
        config=_pipeline_config(
            model_path, oversampling=oversampling, parallel_mode=parallel_mode
        ),
        df=df,
        target="target",
    )
    frame = df.drop(columns=["target"]).iloc[:20]
    loaded = ModelTrainer.load(model_path)
    out = {
        "result": _strip_volatile(result),
        "predictions": loaded.predict(frame),
    }
    ctx["artifacts"][f"pipeline_{name}_{parallel_mode}"] = (model_path, frame)
    return out


