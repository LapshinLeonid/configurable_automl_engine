_ADDRESS = re.compile(r" at 0x[0-9a-fA-F]+")


def _float(value: float) -> str:
    """Exact text form of a float (``repr`` round-trips bit for bit)."""
    if math.isnan(value):
        return "nan"
    return repr(float(value))


def _canon_array(value: Any) -> Any:
    """Canonical form of numpy / scipy / pandas containers (``None`` if not one)."""
    import numpy as np
    import pandas as pd
    import scipy.sparse as sp

    if sp.issparse(value):
        return {
            "sparse": value.format,
            "dtype": str(value.dtype),
            "dense": canon(np.asarray(value.toarray())),
        }
    if isinstance(value, np.ndarray):
        if value.dtype.kind == "f":
            items: Any = [_float(v) for v in value.reshape(-1).tolist()]
        else:
            items = [canon(v) for v in value.reshape(-1).tolist()]
        return {"ndarray": str(value.dtype), "shape": list(value.shape), "v": items}
    if isinstance(value, pd.DataFrame):
        return {
            "DataFrame": [str(c) for c in value.columns],
            "dtypes": [str(d) for d in value.dtypes],
            "index": canon(value.index.to_numpy()),
            "columns": [canon(value[c].to_numpy()) for c in value.columns],
        }
    if isinstance(value, pd.Series):
        return {
            "Series": str(value.name),
            "dtype": str(value.dtype),
            "index": canon(value.index.to_numpy()),
            "v": canon(value.to_numpy()),
        }
    if isinstance(value, pd.Timestamp):
        return {"Timestamp": value.isoformat()}
    return None


def _canon_object(value: Any) -> Any:
    """Canonical form of exceptions, estimators, dataclasses and other objects."""
    if isinstance(value, BaseException):
        return {"exception": type(value).__name__, "message": str(value)}
    if hasattr(value, "get_params") and callable(value.get_params):
        params = value.get_params(deep=False)
        return {"estimator": type(value).__name__, "params": canon(params)}
    if hasattr(value, "__dataclass_fields__"):
        fields = {f: getattr(value, f) for f in value.__dataclass_fields__}
        return {"dataclass": type(value).__name__, "fields": canon(fields)}
    if isinstance(value, enum.Enum):
        return {"enum": type(value).__name__, "value": canon(value.value)}
    if callable(value):
        return {"callable": getattr(value, "__qualname__", type(value).__name__)}
    return {"object": type(value).__name__, "repr": _ADDRESS.sub("", repr(value))}


def canon(value: Any) -> Any:
    """Convert a result into a JSON value that compares exactly.

    Floats become their ``repr`` (bit-exact), arrays and frames keep their
    dtype, estimators become their class name plus ``get_params``. Module
    paths are not recorded: moving a class between modules is not a
    behavior change (pickled paths are checked by the cross-loading).
    """
    import numpy as np

    if value is None or isinstance(value, (bool, str)):
        return value
    if isinstance(value, np.bool_):
        return bool(value)
    if isinstance(value, (int, np.integer)) and not isinstance(value, enum.Enum):
        return int(value)
    if isinstance(value, (float, np.floating)):
        return {"float": _float(float(value))}
    if isinstance(value, dict):
        return {"dict": [[canon(k), canon(v)] for k, v in value.items()]}
    if isinstance(value, (list, tuple)):
        return {type(value).__name__: [canon(v) for v in value]}
    if isinstance(value, (set, frozenset)):
        return {"set": sorted(json.dumps(canon(v), sort_keys=True) for v in value)}
    array = _canon_array(value)
    return array if array is not None else _canon_object(value)


