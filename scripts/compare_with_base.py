def _scenario_sanity_gate() -> dict[str, Any]:
    import numpy as np
    from sklearn.ensemble import RandomForestRegressor
    from sklearn.linear_model import LinearRegression

    from configurable_automl_engine.training_engine.sanity_gate import (
        ModelSanityGate,
    )

    rng = np.random.default_rng(8)
    n = 120
    X = rng.normal(size=(n, 5))
    y = 2.0 * X[:, 0] - X[:, 1] + rng.normal(scale=0.3, size=n)
    lin = LinearRegression().fit(X, y)
    forest = RandomForestRegressor(n_estimators=15, random_state=0).fit(X, y)
    oof = y + rng.normal(scale=0.5, size=n)
    out: dict[str, Any] = {}
    cases = {
        "linear_ok": ({}, oof, lin.predict(X), lin),
        "forest_permutation": ({}, oof, forest.predict(X), forest),
        "constant": ({}, np.full(n, y.mean()), y, lin),
        "rounded": ({}, np.round(oof), lin.predict(X), lin),
        "gap_reject": ({"generalization_gap_mode": "reject"}, oof * 0.2, y, forest),
        "warn_only": ({"warn_only": True}, np.full(n, 1.0), y, lin),
        "no_full": ({}, oof, None, lin),
    }
    for name, (kwargs, y_oof, y_full, model) in cases.items():
        gate = _outcome(ModelSanityGate, **kwargs)
        if isinstance(gate, Exception):
            out[name] = gate
            continue
        out[name] = _outcome(
            gate.check,
            y=y,
            y_pred_oof=y_oof,
            y_pred_full=y_full,
            X=X,
            model=model,
            candidate_name=name,
        )
    out["length_mismatch"] = _outcome(
        lambda: ModelSanityGate().check(y=y, y_pred_oof=oof[:-1])
    )
    return out


def _scenarios() -> dict[str, Callable[[dict[str, Any]], Any]]:
    """All scenarios: name → function of the run context."""
    sc: dict[str, Callable[[dict[str, Any]], Any]] = {}
    for name in _PIPELINES:
        for mode in ("threads", "processes"):
            sc[f"pipeline/{name}/{mode}"] = lambda ctx, n=name, m=mode: (
                _scenario_pipeline(n, m, ctx)
            )
    for name in _trainer_cases():
        sc[f"trainer/{name}"] = lambda ctx, n=name: _scenario_trainer(n, ctx)
    sc["trainer/train_model"] = _scenario_train_model
    for algo in ("ridge", "decision_tree", "elasticnet", "svr"):
        for pruning in (False, True):
            sc[f"optimize/{algo}/pruning={pruning}"] = lambda ctx, a=algo, p=pruning: (
                _scenario_optimize(a, p, ctx)
            )
    for algorithm in ("random", "smote", "adasyn"):
        for kind in ("numeric", "categorical", "sparse"):
            for noise in (False, True):
                for balance in (False, True):
                    sc[
                        f"oversampler/{algorithm}/{kind}/noise={noise}/balance={balance}"
                    ] = lambda ctx, a=algorithm, k=kind, z=noise, b=balance: (
                        _scenario_oversampler(a, k, z, b)
                    )
    sc["direct/validate_features"] = lambda ctx: _scenario_validate_features()
    sc["direct/iter_splits"] = lambda ctx: _scenario_iter_splits()
    sc["direct/create_model"] = lambda ctx: _scenario_create_model()
    sc["direct/sanity_gate"] = lambda ctx: _scenario_sanity_gate()
    return sc


def _cross_load(base_artifacts: Path) -> dict[str, Any]:
    """Load the artifacts saved by the base run and predict with them."""
    import pandas as pd

    from configurable_automl_engine.trainer import ModelTrainer

    index = json.loads((base_artifacts / "index.json").read_text())
    out: dict[str, Any] = {}
    for name, entry in sorted(index.items()):
        frame = pd.read_pickle(entry["frame"])
        loaded = _outcome(ModelTrainer.load, entry["model"])
        if not isinstance(loaded, Exception):
            loaded = _outcome(loaded.predict, frame)
        out[name] = canon(loaded)
    return out


def run_scenarios(out_path: Path, workdir: Path, base_artifacts: Path | None) -> None:
    """Run every scenario on the importable ``src/`` and write the results."""
    import configurable_automl_engine
    from configurable_automl_engine import trainer_state

    expected_src = Path(os.environ["COMPARE_SRC"]).resolve()
    actual = Path(configurable_automl_engine.__file__).resolve().parent.parent
    if actual != expected_src:
        raise SystemExit(f"imported the package from {actual}, not {expected_src}")

    logging.getLogger().setLevel(logging.WARNING)
    collector = _LogCollector()
    pkg_logger = logging.getLogger(PACKAGE)
    pkg_logger.addHandler(collector)
    pkg_logger.setLevel(logging.DEBUG)

    ctx: dict[str, Any] = {"workdir": str(workdir), "artifacts": {}}
    results: dict[str, Any] = {}
    timings: dict[str, float] = {}
    for name, fn in _scenarios().items():
        collector.records = []
        started = time.perf_counter()
        raw = _outcome(fn, ctx)
        if isinstance(raw, Exception):
            value: Any = {"raised": canon(raw)}
            print(f"scenario {name} raised:\n{_tb_tail(raw)}", file=sys.stderr)
        else:
            value = canon(raw)
        entry: dict[str, Any] = {"value": value}
        # Paths of the run's own directory differ between the two runs.
        logs = [
            [lvl, msg.replace(str(workdir), "<workdir>")]
            for lvl, msg in collector.records
        ]
        # Log records of processes-mode runs arrive from the workers in a
        # nondeterministic order, and the forwarding of worker records may
        # drop or repeat one even on identical code: only the results of
        # these runs are compared (the sequential runs compare every record).
        if not name.endswith("/processes"):
            entry["logs"] = logs
        results[name] = entry
        timings[name] = round(time.perf_counter() - started, 2)
    pkg_logger.removeHandler(collector)

    index = {}
    for name, (model, frame) in ctx["artifacts"].items():
        frame_path = workdir / f"{name}.frame.pkl"
        frame.to_pickle(frame_path)
        index[name] = {"model": str(model), "frame": str(frame_path)}
    (workdir / "index.json").write_text(json.dumps(index, indent=1))

    payload = {
        "artifact_format_version": trainer_state.ARTIFACT_FORMAT_VERSION,
        "results": results,
        "own_artifacts": _cross_load(workdir),
        "cross_loaded": _cross_load(base_artifacts) if base_artifacts else None,
        "timings": timings,
    }
    out_path.write_text(json.dumps(payload, indent=1, sort_keys=True))


def _tb_tail(exc: BaseException) -> str:
    lines = traceback.format_exception(type(exc), exc, exc.__traceback__)
    return "".join(lines[-4:])


