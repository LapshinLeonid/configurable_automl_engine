#  Orchestration (runs in the parent process)
# ──────────────────────────────────────────────────────────────────────────────


def _git(*args: str, cwd: Path = REPO_ROOT) -> str:
    return subprocess.run(
        ["git", *args], cwd=cwd, check=True, capture_output=True, text=True
    ).stdout.strip()


def resolve_base(ref: str | None) -> str:
    """The base commit: ``ref``, the merge-base with origin/main, or ``HEAD^``."""
    if ref:
        return _git("rev-parse", "--verify", f"{ref}^{{commit}}")
    head = _git("rev-parse", "HEAD")
    try:
        merge_base = _git("merge-base", "origin/main", "HEAD")
    except subprocess.CalledProcessError:
        merge_base = head
    if merge_base == head:
        return _git("rev-parse", "HEAD^")
    return merge_base


def _run_version(
    label: str,
    src: Path,
    out: Path,
    workdir: Path,
    base_artifacts: Path | None,
) -> None:
    env = dict(os.environ)
    env["PYTHONPATH"] = os.pathsep.join([str(src), env.get("PYTHONPATH", "")])
    env["COMPARE_SRC"] = str(src)
    env["PYTHONHASHSEED"] = "0"
    cmd = [
        sys.executable,
        str(Path(__file__).resolve()),
        "--run-scenarios",
        str(out),
        "--workdir",
        str(workdir),
    ]
    if base_artifacts is not None:
        cmd += ["--base-artifacts", str(base_artifacts)]
    print(f"[compare] running the scenarios on the {label} version ({src})")
    started = time.perf_counter()
    proc = subprocess.run(
        cmd, env=env, cwd=workdir, text=True, capture_output=True, check=False
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout[-4000:] + proc.stderr[-8000:])
        raise SystemExit(f"[compare] the {label} run failed")
    print(f"[compare]   done in {time.perf_counter() - started:.0f}s")


def _generate_schema(checkout: Path, src: Path, workdir: Path) -> bytes:
    """Run the version's own ``schema_generator.py``; return the schema bytes."""
    workdir.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env["PYTHONPATH"] = str(src)
    subprocess.run(
        [sys.executable, str(checkout / "schema_generator.py")],
        cwd=workdir,
        env=env,
        check=True,
        capture_output=True,
    )
    return (workdir / "config.schema.json").read_bytes()


def _flatten(value: Any, path: str, out: dict[str, str]) -> None:
    if isinstance(value, dict):
        for key in value:
            _flatten(value[key], f"{path}.{key}", out)
    elif isinstance(value, list):
        out[f"{path}#len"] = str(len(value))
        for i, item in enumerate(value):
            _flatten(item, f"{path}[{i}]", out)
    else:
        out[path] = json.dumps(value)


def diff_values(base: Any, current: Any, path: str) -> list[str]:
    """Readable differences between two canonical values (empty if equal)."""
    if base == current:
        return []
    flat_b: dict[str, str] = {}
    flat_c: dict[str, str] = {}
    _flatten(base, path, flat_b)
    _flatten(current, path, flat_c)
    lines = []
    for key in sorted(set(flat_b) | set(flat_c)):
        b, c = flat_b.get(key, "<missing>"), flat_c.get(key, "<missing>")
        if b != c:
            lines.append(f"  {key}\n      base:    {b[:300]}\n      current: {c[:300]}")
    return lines


_RETRAIN = re.compile(r"retrain the model")


def compare(
    base: dict[str, Any], current: dict[str, Any], max_lines: int
) -> tuple[list[str], dict[str, int]]:
    """Compare the two runs; return (problems, counters)."""
    problems: list[str] = []
    counts = {"scenarios": 0, "differ": 0, "artifacts": 0}
    names = sorted(set(base["results"]) | set(current["results"]))
    for name in names:
        counts["scenarios"] += 1
        lines = diff_values(
            base["results"].get(name), current["results"].get(name), name
        )
        if lines:
            counts["differ"] += 1
            more = len(lines) - max_lines
            problems.append(f"scenario {name}: {len(lines)} difference(s)")
            problems.extend(lines[:max_lines])
            if more > 0:
                problems.append(f"  ... and {more} more")

    bumped = current["artifact_format_version"] != base["artifact_format_version"]
    for name, own in sorted(base["own_artifacts"].items()):
        counts["artifacts"] += 1
        loaded = (current["cross_loaded"] or {}).get(name)
        if not bumped:
            lines = diff_values(own, loaded, f"cross-load {name}")
            if lines:
                problems.append(
                    f"artifact {name} saved by the base version does not load "
                    "or predict identically in the current one, but "
                    "ARTIFACT_FORMAT_VERSION was not bumped (did a pickled "
                    "class move?)"
                )
                problems.extend(lines[:max_lines])
        else:
            ok = (
                isinstance(loaded, dict)
                and loaded.get("exception") == "TrainingError"
                and _RETRAIN.search(loaded.get("message", ""))
            )
            if not ok:
                problems.append(
                    f"artifact {name}: ARTIFACT_FORMAT_VERSION was bumped "
                    f"({base['artifact_format_version']} -> "
                    f"{current['artifact_format_version']}), so loading the base "
                    f"artifact must raise the 'retrain the model' error; got "
                    f"{json.dumps(loaded)[:300]}"
                )
    return problems, counts


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--base", help="base ref (default: merge-base/HEAD^)")
    parser.add_argument("--max-lines", type=int, default=20)
    parser.add_argument("--keep", action="store_true", help="keep the temp dir")
    parser.add_argument("--run-scenarios", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--workdir", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--base-artifacts", type=Path, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    if args.run_scenarios:
        run_scenarios(args.run_scenarios, args.workdir, args.base_artifacts)
        return 0

    started = time.perf_counter()
    base_sha = resolve_base(args.base)
    head_sha = _git("rev-parse", "HEAD")
    tmp = Path(tempfile.mkdtemp(prefix="compare-with-base-"))
    worktree = tmp / "base"
    print(
        f"[compare] base {base_sha[:10]} vs current working tree (HEAD {head_sha[:10]})"
    )
    _git("worktree", "add", "--detach", "--quiet", str(worktree), base_sha)
    try:
        # The engine version is generated by setuptools-scm into _version.py
        # (not committed): give the base the same one, so that the artifact
        # metadata and the log texts do not differ because of it.
        version_file = REPO_ROOT / "src" / PACKAGE / "_version.py"
        if version_file.exists():
            shutil.copy(version_file, worktree / "src" / PACKAGE / "_version.py")
        base_work, cur_work = tmp / "run-base", tmp / "run-current"
        base_work.mkdir()
        cur_work.mkdir()
        base_json, cur_json = tmp / "base.json", tmp / "current.json"
        _run_version("base", worktree / "src", base_json, base_work, None)
        _run_version("current", REPO_ROOT / "src", cur_json, cur_work, base_work)
        base = json.loads(base_json.read_text())
        current = json.loads(cur_json.read_text())
        problems, counts = compare(base, current, args.max_lines)

        schema_base = _generate_schema(worktree, worktree / "src", tmp / "schema-base")
        schema_cur = _generate_schema(REPO_ROOT, REPO_ROOT / "src", tmp / "schema-cur")
        schema_same = schema_base == schema_cur
        if not schema_same:
            problems.append(
                "config schema: the output of schema_generator.py differs "
                f"(base {len(schema_base)} bytes, current {len(schema_cur)} bytes)"
            )
    finally:
        _git("worktree", "remove", "--force", str(worktree))
        if not args.keep:
            shutil.rmtree(tmp, ignore_errors=True)
        else:
            print(f"[compare] kept {tmp}")

    for line in problems:
        print(line)
    fmt = f"{base['artifact_format_version']} -> {current['artifact_format_version']}"
    status = "CLEAN" if not problems else "DIFFERENT"
    print(
        f"[compare] {status}: {counts['scenarios']} scenarios "
        f"({counts['differ']} differ), {counts['artifacts']} cross-loaded artifacts "
        f"(format {fmt}), schema {'identical' if schema_same else 'DIFFERS'}; "
        f"base {base_sha[:10]}, {time.perf_counter() - started:.0f}s"
    )
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main())
