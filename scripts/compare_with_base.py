def _trainer_frame(seed: int = 11, n: int = 90) -> tuple[Any, Any]:
    import numpy as np
    import pandas as pd

    rng = np.random.default_rng(seed)
    X = pd.DataFrame(
        {
            "a": rng.normal(size=n),
            "b": rng.normal(size=n),
            "c": rng.normal(size=n),
            "color": rng.choice(["red", "green", "blue"], size=n),
            "shop": rng.choice([f"s{i}" for i in range(9)], size=n),
        }
    )
    X.loc[[3, 17, 41], "b"] = np.nan
    X.loc[[5, 60], "color"] = np.nan
    y = pd.Series(
        3.0 * X["a"] - X["c"] + (X["color"] == "red") + rng.normal(scale=0.2, size=n),
        name="y",
    )
    return X, y


