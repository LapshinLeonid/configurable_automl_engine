"""Differential behavior check: compare the current ``src/`` with a base commit.

The package's results depend on the installed versions of scikit-learn,
XGBoost, numpy and the other libraries, so stored expected outputs
(snapshots) break on every library update. This script stores nothing:
it runs one set of scenarios twice, **with the same interpreter and the
same installed libraries**, once on the base commit's ``src/`` and once on
the current ``src/``, and fails on any difference.

Steps:

1. Resolve the base ref (``--base``; default ``git merge-base origin/main
   HEAD``, or ``HEAD^`` when ``HEAD`` is on ``origin/main`` itself).
2. Check the base out into a temporary ``git worktree``.
3. Run the scenarios of this file (``--run-scenarios``) on the base ``src/``
   and then on the current ``src/``; each run writes its results to JSON.
   The current run also loads the models saved by the base run
   (cross-loading).
4. Compare the two JSON files: results exactly (floats bit for bit),
   exception types and messages, log texts and levels, the config schema
   generated by each version's ``schema_generator.py`` (byte for byte).
   A base artifact must load in the current version and predict
   identically, unless ``ARTIFACT_FORMAT_VERSION`` was bumped, in which
   case loading must raise the "retrain the model" error.

Usage::

    python scripts/compare_with_base.py              # merge-base with origin/main
    python scripts/compare_with_base.py --base main~3

The script lives outside the package, so it is not subject to the import
layers. The scenarios use the public API only; they must work on both the
base and the current version.
"""

