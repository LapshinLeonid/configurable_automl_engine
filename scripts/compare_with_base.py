class _LogCollector(logging.Handler):
    """Collect (logger prefix, level, message) of the package's log records."""

    def __init__(self) -> None:
        super().__init__(level=logging.DEBUG)
        self.records: list[list[str]] = []

    def emit(self, record: logging.LogRecord) -> None:
        self.records.append([record.levelname, record.getMessage()])


def _outcome(fn: Callable[..., Any], *args: Any, **kwargs: Any) -> Any:
    """The result of ``fn(*args, **kwargs)``, or the exception it raised.

    An exception is a result too: its type and message are compared.
    """
    try:
        return fn(*args, **kwargs)
    except Exception as exc:  # noqa: BLE001
        return exc


def _numeric_df(seed: int = 20240501, n: int = 80) -> Any:
    import numpy as np
    import pandas as pd

    rng = np.random.default_rng(seed)
    X = rng.normal(size=(n, 4))
    y = 10.0 + 2.0 * X[:, 0] - 1.5 * X[:, 1] + 0.5 * X[:, 2] ** 2
    y = y + rng.normal(scale=0.3, size=n)
    df = pd.DataFrame(X, columns=["x1", "x2", "x3", "x4"])
    df["target"] = np.abs(y) + 0.1
    return df


def _mixed_df(seed: int = 20240502, n: int = 300) -> Any:
    import numpy as np
    import pandas as pd

    rng = np.random.default_rng(seed)
    x1 = rng.normal(size=n)
    x2 = rng.uniform(0.0, 5.0, size=n)
    city = rng.choice(["north", "south", "east", "west"], size=n)
    effect = pd.Series(city).map(
        {"north": 3.0, "south": -1.0, "east": 0.5, "west": 1.5}
    )
    ts = pd.Timestamp("2021-01-01") + pd.to_timedelta(
        rng.integers(0, 720, size=n), unit="D"
    )
    y = 20.0 + 2.5 * x1 + 1.2 * x2 + effect.to_numpy()
    y = y + rng.normal(scale=0.5, size=n)
    df = pd.DataFrame({"x1": x1, "x2": x2, "city": city, "when": ts, "target": y})
    df.loc[rng.choice(n, size=15, replace=False), "x2"] = np.nan
    df.loc[rng.choice(n, size=12, replace=False), "city"] = np.nan
    return df


