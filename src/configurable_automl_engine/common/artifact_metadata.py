"""Artifact metadata of a saved ``ModelTrainer``.

Collects the environment and configuration metadata recorded in a saved
artifact (``ModelTrainer.artifact_metadata_``: the artifact format version,
the engine and dependency versions, the creation timestamp, the algorithm,
the hyperparameters and a configuration hash), refuses at load time an
artifact of another format version (``check_artifact_format``) and warns
when the artifact was created with a different ``major.minor`` version of
the engine or scikit-learn. It must not import
``configurable_automl_engine.trainer``.
"""

from __future__ import annotations

import datetime as dt
import hashlib
import importlib
import json
import logging
import platform
from typing import TYPE_CHECKING, Any, cast

from configurable_automl_engine.trainer_errors import TrainingError
from configurable_automl_engine.trainer_state import ARTIFACT_FORMAT_VERSION

if TYPE_CHECKING:
    from configurable_automl_engine.trainer_state import TrainerSettings

# The engine version is generated by setuptools-scm into ``_version.py``.
# It is recorded in artifact metadata and used for load-time compatibility
# warnings. The fallback covers a fresh checkout without a generated file.
try:
    from configurable_automl_engine._version import __version__ as _engine_version
except ImportError:  # pragma: no cover - _version.py absent in a fresh checkout
    _engine_version = "0.0.0"

#: Artifact dependency versions that are recorded in ``artifact_metadata_``
#: and checked at load time against the current environment. Each value is a
#: (package name, importable module name) pair.
_ARTIFACT_VERSION_PACKAGES: tuple[tuple[str, str], ...] = (
    ("python", "sys"),
    ("numpy", "numpy"),
    ("pandas", "pandas"),
    ("scikit-learn", "sklearn"),
    ("optuna", "optuna"),
    ("imbalanced-learn", "imblearn"),
    ("xgboost", "xgboost"),
)


def _version_tuple(version: str) -> tuple[int | str, ...]:
    """Parse a ``major.minor.patch`` version string into a comparable tuple.

    Non-numeric components (e.g. ``dev``, ``rc``, ``post``) are kept as strings
    so that ``major.minor`` comparisons stay meaningful and stable.

    Args:
        version: The version string.

    Returns:
        The parsed version components as a tuple.
    """
    parts: list[int | str] = []
    for part in str(version).split("."):
        try:
            parts.append(int(part))
        except ValueError:
            parts.append(part)
    return tuple(parts)


def _major_minor(version: str) -> tuple[int, int] | None:
    """Return the ``(major, minor)`` pair of a version string, if parseable.

    Args:
        version: The version string.

    Returns:
        The ``(major, minor)`` pair, or ``None`` when the version has fewer
        than two numeric components.
    """
    parts = _version_tuple(version)
    if len(parts) < 2 or not isinstance(parts[0], int) or not isinstance(parts[1], int):
        return None
    return (parts[0], parts[1])


def _installed_module_version(module_name: str) -> str | None:
    """Return the ``__version__`` of an installed module, if available.

    Args:
        module_name: Name of the module to import (``'sys'`` for Python itself).

    Returns:
        The module version string, or ``None`` if the module is missing or
        exposes no ``__version__``.
    """
    if module_name == "sys":
        return platform.python_version()
    try:
        module = importlib.import_module(module_name)
    except Exception:  # noqa: BLE001 - an optional dependency may be absent
        return None
    return cast(str | None, getattr(module, "__version__", None))


def _collect_artifact_metadata(settings: TrainerSettings) -> dict[str, Any]:
    """Collect the artifact metadata dict for :meth:`ModelTrainer.save`.

    The metadata captures the artifact format version, the environment
    (engine version, Python, and the versions of the ML stack), the creation
    timestamp in UTC, and the algorithm configuration (algorithm,
    hyperparameters, and a content hash of the configuration).

    Args:
        settings: The settings of the trainer being saved.

    Returns:
        The metadata dictionary.
    """
    deps: dict[str, str | None] = {}
    for package_name, module_name in _ARTIFACT_VERSION_PACKAGES:
        deps[package_name] = _installed_module_version(module_name)
    # The engine itself is part of the recorded environment; the top-level
    # ``engine_version`` key is kept for convenient access.
    deps["configurable_automl_engine"] = _engine_version

    config_blob = json.dumps(
        {
            "algorithm": settings.algorithm,
            "hyperparams": settings.hyperparams,
            "metric": settings.metric,
            "random_state": settings.random_state,
            "serialization_format": settings.serialization_format.value,
            "validation_strategy": settings.validation_strategy,
            "n_folds": settings.n_folds,
            "test_size": settings.test_size,
            "encoding_strategy": settings.encoding.encoding,
        },
        default=str,
        sort_keys=True,
    )
    config_hash = hashlib.sha256(config_blob.encode("utf-8")).hexdigest()

    return {
        "artifact_format_version": ARTIFACT_FORMAT_VERSION,
        "engine_version": _engine_version,
        "python_version": deps["python"],
        "versions": deps,
        "created_at_utc": dt.datetime.now(dt.UTC).isoformat(),
        "algorithm": settings.algorithm,
        "params": dict(settings.hyperparams),
        "config_hash": config_hash,
    }


def check_artifact_format(metadata: Any) -> None:
    """Refuse an artifact whose format version is not the current one.

    Artifacts saved by the engine up to 0.4.x carry no format version (the
    flat ``ModelTrainer`` attributes, format 1); their state cannot be
    restored into the grouped state of the current format.

    Args:
        metadata: The ``artifact_metadata_`` of the loaded object (``None``
            for an artifact saved without metadata).

    Raises:
        TrainingError: If the artifact format version is not
            ``ARTIFACT_FORMAT_VERSION``; the message names both engine
            versions and says to retrain the model.
    """
    meta = metadata if isinstance(metadata, dict) else {}
    version = meta.get("artifact_format_version", 1)
    if version == ARTIFACT_FORMAT_VERSION:
        return
    saved_by = meta.get("engine_version") or "<= 0.4.x"
    raise TrainingError(
        f"The artifact was saved by engine {saved_by} (artifact format "
        f"{version}), which engine {_engine_version} (artifact format "
        f"{ARTIFACT_FORMAT_VERSION}) cannot load; retrain the model with "
        f"engine {_engine_version}."
    )


def _warn_on_version_mismatch(metadata: Any, logger: logging.Logger) -> None:
    """Emit a warning when the artifact's engine or scikit-learn major/minor
    version differs from the one in the current environment.

    Only the engine version and scikit-learn are checked (the packages most
    likely to break pickled models); the comparison is restricted to the
    ``major.minor`` pair so that patch-level differences do not produce noise.

    Args:
        metadata: The artifact metadata dict read from the saved object.
        logger: The logger to emit the warning on.
    """
    if not isinstance(metadata, dict):
        return
    versions = metadata.get("versions")
    if not isinstance(versions, dict):
        return
    current_sklearn = _installed_module_version("sklearn")
    for key, current in (
        ("configurable_automl_engine", _engine_version),
        ("scikit-learn", current_sklearn),
    ):
        stored = _major_minor(str(versions.get(key, "")))
        current_pair = _major_minor(str(current)) if current else None
        if stored is not None and current_pair is not None and stored != current_pair:
            logger.warning(
                "Artifact was created with %s %s but the current environment "
                "has %s %s. Loading may fail or produce unexpected results; "
                "consider retraining the model with the current version.",
                key,
                versions.get(key),
                key,
                current,
            )
